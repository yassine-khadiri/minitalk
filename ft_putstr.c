#include "minitalk.h"

void	ft_putstr(char *s)
{
	int	i;

	i = 0;
	if (s == NULL)
		return (ft_putstr("(null)"));
	if (s != NULL)
	{
		while (s[i] != '\0')
			ft_putchar(s[i++]);
	}
}
